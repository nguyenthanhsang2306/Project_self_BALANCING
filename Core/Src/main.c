void App_UART_RxIRQ(USART_TypeDef *uart)
{
  if (!uart) return;
  uint32_t isr = uart->ISR;
  if (isr & (USART_ISR_ORE | USART_ISR_FE | USART_ISR_NE | USART_ISR_PE))
  {
    uart->ICR = USART_ICR_ORECF | USART_ICR_FECF | USART_ICR_NCF | USART_ICR_PECF;
  }
  while (uart->ISR & USART_ISR_RXNE)
  {
    (void)uart->RDR;
  }
}

int main(void)
{
  HAL_Init();
  SystemClock_Config();

  MX_GPIO_Init();
  MX_USART2_UART_Init();
  MX_I2C1_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_TIM6_Init();

  CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
  DWT->CYCCNT = 0;
  DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
  __HAL_DBGMCU_FREEZE_TIM6();

  (void)Motor_Init(&motor_sys, &htim1, &htim2, &htim3);
  if (ICM20602_Init(&imu, &hi2c1))
  {
    ICM20602_SetAxis(&imu, IMU_TILT_AXIS);
    (void)ICM20602_Calibrate(&imu, IMU_CALIB_SAMPLES);
  }

  __HAL_TIM_CLEAR_FLAG(&htim6, TIM_FLAG_UPDATE);
  (void)HAL_TIM_Base_Start(&htim6);
  last_cycles = DWT->CYCCNT;

  while (1)
  {
    if (__HAL_TIM_GET_FLAG(&htim6, TIM_FLAG_UPDATE) != RESET)
    {
      __HAL_TIM_CLEAR_FLAG(&htim6, TIM_FLAG_UPDATE);
      uint32_t now_cycles = DWT->CYCCNT;
      float dt = last_cycles ? ((float)(now_cycles - last_cycles) / (float)SystemCoreClock) : 0.005f;
      last_cycles = now_cycles;

      if (isfinite(dt) && dt >= 0.001f)
      {
        if (dt > 0.030f) dt = 0.030f;
        if (motor_sys.enc_ready) Motor_ReadEncoders(&motor_sys);
        if (imu.ready) (void)ICM20602_UpdateAngle(&imu, dt);
      }
    }

    /* Heartbeat LED LD2: nháy chậm 500ms báo bộ khung phần cứng đang chạy */
    HAL_GPIO_WritePin(LD2_GPIO_Port, LD2_Pin, ((HAL_GetTick() / 500U) & 1U) ? GPIO_PIN_SET : GPIO_PIN_RESET);
  }
}

